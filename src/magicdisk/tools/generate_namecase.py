#!/usr/bin/env python3
"""Generate the pinned simple-uppercase table; normal builds need no download."""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
expected = '5e444028b6e76d96f9dc509609c5e3222bf609056f35e5fcde7e6fb8a58cd446'
if hashlib.sha256(source).hexdigest() != expected:
    raise SystemExit('Expected the official UnicodeData-3.2.0.txt, with its original bytes')

pairs = []
for line in source.decode('ascii').splitlines():
    fields = line.split(';')
    if fields[12]:
        pairs.append((int(fields[0], 16), int(fields[12], 16)))

print('/* Generated by tools/generate_namecase.py. Do not edit.')
print('   Unicode 3.2 simple uppercase mappings; see UNICODE-LICENSE.txt.')
print('   https://www.unicode.org/Public/3.2-Update/UnicodeData-3.2.0.txt')
print('   SHA-256: ' + expected + ' */')
print('static const struct {')
print('    dt_u32 lower, upper;')
print('} name_case[] = {')
for lower, upper in pairs:
    print(f'    {{0x{lower:05x}UL, 0x{upper:05x}UL}},')
print('};')
