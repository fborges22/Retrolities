#!/usr/bin/env python3
"""Generate OEM decoding and pinned Unicode lowercase display tables."""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
expected = '5e444028b6e76d96f9dc509609c5e3222bf609056f35e5fcde7e6fb8a58cd446'
if hashlib.sha256(source).hexdigest() != expected:
    raise SystemExit('Expected the official UnicodeData-3.2.0.txt, with its original bytes')
lowercase = {}
for line in source.decode('ascii').splitlines():
    fields = line.split(';')
    if fields[13]:
        lowercase[int(fields[0], 16)] = int(fields[13], 16)

print('/* Generated by tools/generate_oemcode.py. Do not edit.')
pages = [437, 850, 852, 860, 866]
print('   Explicit OEM decoding (Python codecs); no encoding is inferred.')
for cp in pages:
    print(f'   https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/PC/CP{cp}.TXT')
print('   Simple lowercase: UnicodeData-3.2.0.txt; see UNICODE-LICENSE.txt.')
print('   SHA-256: ' + expected + ' */')
for cp in pages:
    values = [ord(bytes([value]).decode(f'cp{cp}')) for value in range(128, 256)]
    for suffix, table in [('', values), ('_lower', [lowercase.get(ch, ch) for ch in values])]:
        print(f'static const unsigned short oem_{cp}{suffix}[128] = {{')
        for start in range(0, 128, 8):
            print('    ' + ', '.join(f'0x{ch:04x}' for ch in table[start:start + 8]) + ',')
        print('};')

print('typedef struct {')
print('    unsigned page;')
print('    const unsigned short *decode, *lower;')
print('} OemCodepage;')
print('static const OemCodepage oem_pages[] = {')
for cp in pages:
    print(f'    {{{cp}, oem_{cp}, oem_{cp}_lower}},')
print('};')
