# name -> (tool glyph, hotspot)
CURSORS = {'pencil': ('pencil', (1, 14)), 'fill': ('fill', (1, 13)),
           'picker': ('picker', (1, 13)), 'zoom': ('zoom', (4, 4)),
           'brush': ('brush', (1, 14)), 'spray': ('spray', (2, 3)),
           'eraser': ('eraser', (3, 10))}


def grid(art, name):
    rows = art.strip('\n').split('\n')
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise SystemExit('glyph %s is not 16x16: %r' % (name, [len(r) for r in rows]))
    return rows


def bmp_rows(pixels, bpp):
    """pixels: list of rows (top-down) of palette indices -> bottom-up bits."""
    out = b''
    for row in reversed(pixels):
        if bpp == 4:
            row = row + [0] * (len(row) % 2)
            data = bytes((row[i] << 4) | row[i + 1] for i in range(0, len(row), 2))
        else:
            row = row + [0] * (-len(row) % 8)
            data = bytes(sum(row[i + j] << (7 - j) for j in range(8))
                         for i in range(0, len(row), 8))
        out += data + b'\0' * (-len(data) % 4)
    return out


def header(w, h, bpp):
    return struct.pack('<IiiHHIIiiII', 40, w, h, 1, bpp, 0, 0, 0, 0, 0, 0)


def table(colors):
    return b''.join(struct.pack('<BBBB', b, g, r, 0) for r, g, b in colors)


def write_bmp(name, pixels, bpp, colors):
    body = header(len(pixels[0]), len(pixels), bpp) + table(colors) + bmp_rows(pixels, bpp)
    off = 14 + 40 + 4 * len(colors)
    with open(os.path.join(OUT, name), 'wb') as f:
        f.write(struct.pack('<2sIHHI', b'BM', 14 + len(body), 0, 0, off) + body)


def strip(glyphs, order, name, dark_name=None):
    rows = [[] for _ in range(16)]
    dark = [[] for _ in range(16)]
    for g in order:
        for y, line in enumerate(grid(glyphs[g], g)):
            # Transparent pixels are stored as silver; the program masks them.
            rows[y] += [KEY.get(ch, 8) for ch in line]
            dark[y] += [0 if ch in DARK else 1 for ch in line]
    write_bmp(name, rows, 4, VGA)
    mask = [[0 if ch != '.' else 1 for ch in ''.join(grid(glyphs[g], g)[y] for g in order)]
            for y in range(16)]
    write_bmp(name.replace('.bmp', 'm.bmp'), mask, 1, [(0, 0, 0), (255, 255, 255)])
    if dark_name:
        write_bmp(dark_name, dark, 1, [(0, 0, 0), (255, 255, 255)])


def write_icon_file(name, kind, xor_bpp, xor, and_mask, colors, hot=(0, 0)):
    size = len(xor)
    image = (struct.pack('<IiiHHIIiiII', 40, size, size * 2, 1, xor_bpp, 0, 0, 0, 0, 0, 0)
             + table(colors) + bmp_rows(xor, xor_bpp) + bmp_rows(and_mask, 1))
    if kind == 1:
        entry = struct.pack('<BBBBHHII', size, size, len(colors) & 255, 0, 1, xor_bpp, len(image), 22)
    else:
        entry = struct.pack('<BBBBHHII', size, size, 0, 0, hot[0], hot[1], len(image), 22)
    with open(os.path.join(OUT, name), 'wb') as f:
        f.write(struct.pack('<HHH', 0, kind, 1) + entry + image)


def cursor(name, glyph, hot):
    g = grid(TOOLS[glyph], glyph)
    xor = [[0] * 32 for _ in range(32)]
    andm = [[1] * 32 for _ in range(32)]
    ox, oy = 1, 1
    solid = set()
    for y in range(16):
        for x in range(16):
            if g[y][x] != '.':
                solid.add((x, y))
    for (x, y) in solid:                       # white halo
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                andm[y + oy + dy][x + ox + dx] = 0
                xor[y + oy + dy][x + ox + dx] = 1
    for (x, y) in solid:
        xor[y + oy][x + ox] = 0 if g[y][x] in DARK else 1
    write_icon_file(name + '.cur', 2, 1, xor, andm, [(0, 0, 0), (255, 255, 255)],
                    (hot[0] + ox, hot[1] + oy))


def app_icon():
    """A painter's palette with colour dabs and a brush, 32x32."""
    T = -1
    px = [[T] * 32 for _ in range(32)]

    def inside(x, y):
        # palette body: a slightly rotated ellipse with a thumb hole
        a = math.radians(-18)
        dx, dy = x - 15.0, y - 17.5
        u = dx * math.cos(a) - dy * math.sin(a)
        v = dx * math.sin(a) + dy * math.cos(a)
        if (u / 14.6) ** 2 + (v / 10.6) ** 2 > 1.0:
            return False
        if (x - 9.5) ** 2 + (y - 22.0) ** 2 < 2.6 ** 2:
            return False
        return True

    for y in range(32):
        for x in range(32):
            if inside(x, y):
                px[y][x] = 11 if (x + y) % 2 or y < 16 else 3      # wood: yellow / olive
    for y in range(32):                                            # lower shading
        for x in range(32):
            if px[y][x] != T and not inside(x - 1, y - 2):
                px[y][x] = 15
            elif px[y][x] != T and not inside(x + 1, y + 2):
                px[y][x] = 3
    dabs = [(8, 14, 9), (13, 10, 12), (19, 9, 10), (24, 12, 13), (25, 18, 14), (19, 23, 15)]
    for cx, cy, col in dabs:
        for y in range(32):
            for x in range(32):
                d = (x - cx) ** 2 + (y - cy) ** 2
                if d <= 5:
                    px[y][x] = col
        px[cy - 1][cx - 1] = 15
    # outline everything drawn so far
    snap = [row[:] for row in px]
    for y in range(32):
        for x in range(32):
            if snap[y][x] == T:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < 32 and 0 <= yy < 32 and snap[yy][xx] != T:
                        px[y][x] = 0
    # brush: from top-right down to the middle of the palette
    for i in range(0, 17):
        x, y = 30 - i, 1 + i
        if i < 10:                       # handle
            for d, c in ((-1, 0), (0, 9), (1, 1), (2, 0)):
                if 0 <= x + d < 32:
                    px[y][x + d] = c
        elif i < 12:                     # ferrule
            for d, c in ((-1, 0), (0, 15), (1, 8), (2, 7), (3, 0)):
                px[y][x + d] = c
        else:                            # bristles
            w = 16 - i
            for d in range(-1, w + 2):
                px[y][x + d] = 0 if d in (-1, w + 1) else 4
    px[18][13] = 0
    xor = [[0 if c == T else c for c in row] for row in px]
    andm = [[1 if c == T else 0 for c in row] for row in px]
    write_icon_file('picasso.ico', 1, 4, xor, andm, VGA)


def main():
    TOOLBAR['redo'] = '\n'.join(r[::-1] for r in grid(TOOLBAR['undo'], 'undo'))
    strip(TOOLBAR, TOOLBAR_ORDER, 'toolbar.bmp', 'toolbard.bmp')
    strip(TOOLS, TOOLS_ORDER, 'tools.bmp')
    for name, (glyph, hot) in CURSORS.items():
        cursor(name, glyph, hot)
    app_icon()


if __name__ == '__main__':
    main()
