#!/usr/bin/env python3
"""bin2c.py OUT.c name=file ... : embed binaries as far arrays for Open Watcom."""
import sys

out = [ '/* generated by tools/bin2c.py */\n' ]
for arg in sys.argv[2:]:
    name, path = arg.split('=', 1)
    data = open(path, 'rb').read()
    out.append(f'const unsigned int {name}_len = {len(data)};\n')
    out.append(f'const unsigned char __far {name}[{len(data)}] = {{\n')
    for i in range(0, len(data), 16):
        out.append('    ' + ','.join(str(b) for b in data[i:i + 16]) + ',\n')
    out.append('};\n')
open(sys.argv[1], 'w').write(''.join(out))
